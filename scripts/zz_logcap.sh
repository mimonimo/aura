#!/bin/bash
# 주기 작업 기록 파일이 상한(기본 200MB)을 넘으면 직전 판 하나(.1)만 남기고 새로 시작한다.
# 그래프 다시 짓기 한 번에 수만 줄이 쌓여 /tmp/zz_sync.log 가 끝없이 커지던 것(10-15 기준 730MB)을 막는다.
# 쓰고 있는 다른 작업은 옮겨진 파일에 이어 쓰고, 다음 회차부터 새 파일에 쓴다.
cap=$(( ${ZZ_LOG_CAP_MB:-200} * 1024 * 1024 ))
for f in "$@"; do
    [ -f "$f" ] || continue
    [ "$(stat -c %s "$f")" -gt "$cap" ] && mv -f "$f" "$f.1"
done
exit 0
